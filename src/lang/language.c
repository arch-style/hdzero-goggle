struct Language {
    lang_e lang;
    const char *const code;
    const char *const name;
    const translate_t *translations;
};

static struct Language languages[] = {
    {LANG_ENGLISH_DEFAULT, "en_us", "English", NULL},
    {LANG_SIMPLIFIED_CHINESE, "zh_hans", "Simplified Chinese", NULL},
    {LANG_RUSSIAN, "ru_ru", "Russian", NULL},
    {LANG_SPANISH, "es_es", "Spanish", NULL},
    {LANG_JAPANESE, "ja_jp", "Japanese", NULL},
    {LANG_GERMAN, "de_de", "German", NULL},
};

const char *language_config_file[] = {
    // uppercase
    "ENG.TXT",
    "CHN.TXT",
    "RUS.TXT",
    "SPA.TXT",
    "JPN.TXT",
    "GER.TXT",
};

struct CallbackPayload {
    translate_t translations[TRANSLATE_STRING_NUM];
    size_t index;
};

int init_callback(const char *section, const char *key, const char *value, void *userData) {
    struct CallbackPayload *payload = userData;

    (void)section;

    assert(key != NULL);
    assert(value != NULL);

    if (payload->index >= TRANSLATE_STRING_NUM) {
        LOGE("Translation table is full, skipping key: %s", key);
        return 1;
    }

    const size_t englishLength = strlen(key);
    const size_t translateLength = strlen(value);

    char *englishBuffer = malloc(englishLength + 1);
    char *translateBuffer = malloc(translateLength + 1);

    strncpy(englishBuffer, key, englishLength);
    strncpy(translateBuffer, value, translateLength);

    englishBuffer[englishLength] = 0;
    translateBuffer[translateLength] = 0;

    payload->translations[payload->index].in_english = englishBuffer;
    payload->translations[payload->index].translate = translateBuffer;

    payload->index++;
    return 1;
}

// The translations this build was made with, from mkapp/app/language
// (language_builtin.c, generated by src/lang/embed_languages.cmake).
extern const struct {
    const char *code;
    const unsigned char *data;
    size_t size;
} language_builtin[];

#define LANG_BUILTIN_FOLDER "/tmp/language"

// Run from the SD card, this app reads its translations from the goggle's own
// firmware, which need not be the one it was built with: on a goggle 2 with
// 9.5.1 installed there is no Japanese, German or Spanish at all, and the
// Chinese and Russian are 286 strings of 384. So the files built in are
// written out to /tmp (minIni reads files) and read from there; the
// firmware's folder is only the fallback for a language not built in.
static bool language_builtin_file(const char *code, char *path, size_t size) {
    static bool folder_made = false;

    for (size_t i = 0; language_builtin[i].code; i++) {
        if (strcmp(language_builtin[i].code, code) != 0)
            continue;

        if (!folder_made) {
            mkdir(LANG_BUILTIN_FOLDER, 0755);
            folder_made = true;
        }
        snprintf(path, size, "%s/%s.ini", LANG_BUILTIN_FOLDER, code);

        FILE *fp = fopen(path, "wb");
        if (!fp)
            return false;
        const bool ok = fwrite(language_builtin[i].data, 1, language_builtin[i].size, fp) == language_builtin[i].size;
        return fclose(fp) == 0 && ok;
    }
    return false;
}

void language_init() {
    for (size_t i = 0; i < ARRAY_SIZE(languages); i++) {
        char fileName[256];
        bool builtin = language_builtin_file(languages[i].code, fileName, sizeof(fileName));

        if (!builtin)
            sprintf(fileName, "%s/%s.ini", LANG_FOLDER, languages[i].code);

        INI_FILETYPE file;
        if (!ini_openread(fileName, &file)) {
            LOGE("Failed to open %s", fileName);
            languages[i].translations = NULL;
            continue;
        }

        // Load translations
        translate_t *translations = calloc(TRANSLATE_STRING_NUM, sizeof(translate_t));
        struct CallbackPayload payload = {.index = 0};
        ini_browse(init_callback, &payload, fileName);

        // Copy translations
        memcpy(translations, payload.translations, sizeof(payload.translations));
        languages[i].translations = translations;

        // The table itself used to go to the log, all three languages of it
        // at every boot: 575 lines and a fifth of the file, to say what one
        // count says. A short table means the file on the card is out of date
        // against TRANSLATE_STRING_NUM, which is the only thing anyone ever
        // looked for here.
        LOGI("language: %s loaded %zu of %d strings%s",
             languages[i].code, payload.index, TRANSLATE_STRING_NUM, builtin ? ", built in" : "");

        ini_close(&file);
    }
}

const char *translate_string(const char *str, lang_e lang) {
    if (lang == LANG_ENGLISH_DEFAULT || lang >= LANG_END)
        return str;

    const struct Language *const language = &languages[lang];
    const size_t keyLength = strlen(str);
    // search str translate
    for (int i = 0; i < TRANSLATE_STRING_NUM; i++) {
        const translate_t *const translation = &language->translations[i];

        if (translation->in_english == NULL || translation->in_english[0] == '\0')
            continue;

        if (strlen(translation->in_english) != keyLength)
            continue;

        if (strcmp(str, translation->in_english) == 0)
            return translation->translate;
    }

    return str;
}

static void to_lowercase(char *str) {
    while (*str) {
        if (isupper((unsigned char)*str)) {
            *str = tolower((unsigned char)*str);
        }
        str++;
    }
}

bool language_config() {
    char buf[256];
    int i = 0;

    for (i = 0; i < LANG_END; i++) {
        snprintf(buf, sizeof(buf), "/mnt/extsd/%s", language_config_file[i]);
        if (access(buf, F_OK) == 0) {
            LOGI("%s found", language_config_file[i]);
            ini_putl("language", "lang", i, SETTING_INI);
            g_setting.language.lang = i;
            return true;
        }

        to_lowercase(buf);
        if (access(buf, F_OK) == 0) {
            LOGI("%s found", language_config_file[i]);
            ini_putl("language", "lang", i, SETTING_INI);
            g_setting.language.lang = i;
            return true;
        }
    }
    return false;
}
